"""Compile gui/src/framegen/framegen_kernels.cu to PTX with NVRTC and embed it as a header.

The PTX targets compute_75 (Turing, the first GPUs with the NVIDIA optical flow
accelerator), and the driver JIT-compiles it for newer GPUs, including Blackwell.

Usage:
    python3 scripts/framegen/gen_ptx.py [--nvrtc /path/to/libnvrtc.so.12]

NVRTC comes with the CUDA toolkit, or from PyPI: pip install nvidia-cuda-nvrtc-cu12
"""

import argparse
import ctypes
import ctypes.util
import glob
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "gui", "src", "framegen", "framegen_kernels.cu")
OUT = os.path.join(ROOT, "gui", "src", "framegen", "framegen_kernels_ptx.h")
ARCH = "compute_75"


def find_nvrtc(explicit):
    if explicit:
        return explicit
    candidates = []
    for path in sys.path:
        candidates += glob.glob(os.path.join(path, "nvidia", "cuda_nvrtc", "lib", "libnvrtc.so.*"))
        candidates += glob.glob(os.path.join(path, "nvidia", "cuda_nvrtc", "bin", "nvrtc64_*.dll"))
    cuda_path = os.environ.get("CUDA_PATH")
    if cuda_path:
        candidates += glob.glob(os.path.join(cuda_path, "bin", "nvrtc64_*.dll"))
        candidates += glob.glob(os.path.join(cuda_path, "lib64", "libnvrtc.so*"))
    candidates = [c for c in candidates if "builtins" not in os.path.basename(c) and ".alt." not in c]
    if candidates:
        return sorted(candidates)[-1]
    return ctypes.util.find_library("nvrtc")


def compile_ptx(nvrtc_path, source):
    lib = ctypes.CDLL(nvrtc_path)
    prog = ctypes.c_void_p()
    check = lambda r, what: (_ for _ in ()).throw(RuntimeError(f"{what} failed: {r}")) if r != 0 else None
    check(lib.nvrtcCreateProgram(ctypes.byref(prog), source.encode(), b"framegen_kernels.cu", 0, None, None),
          "nvrtcCreateProgram")
    opts = [f"--gpu-architecture={ARCH}".encode(), b"--std=c++14", b"-default-device", b"--use_fast_math"]
    opts_arr = (ctypes.c_char_p * len(opts))(*opts)
    result = lib.nvrtcCompileProgram(prog, len(opts), opts_arr)
    log_size = ctypes.c_size_t()
    lib.nvrtcGetProgramLogSize(prog, ctypes.byref(log_size))
    log = ctypes.create_string_buffer(log_size.value)
    lib.nvrtcGetProgramLog(prog, log)
    if log.value.strip():
        print(log.value.decode(), file=sys.stderr)
    check(result, "nvrtcCompileProgram")
    ptx_size = ctypes.c_size_t()
    check(lib.nvrtcGetPTXSize(prog, ctypes.byref(ptx_size)), "nvrtcGetPTXSize")
    ptx = ctypes.create_string_buffer(ptx_size.value)
    check(lib.nvrtcGetPTX(prog, ptx), "nvrtcGetPTX")
    major, minor = ctypes.c_int(), ctypes.c_int()
    lib.nvrtcVersion(ctypes.byref(major), ctypes.byref(minor))
    lib.nvrtcDestroyProgram(ctypes.byref(prog))
    return ptx.value, f"{major.value}.{minor.value}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--nvrtc", help="path to the NVRTC shared library")
    args = parser.parse_args()
    nvrtc = find_nvrtc(args.nvrtc)
    if not nvrtc:
        sys.exit("NVRTC not found; install the CUDA toolkit or `pip install nvidia-cuda-nvrtc-cu12`")
    with open(SRC, "r", encoding="utf-8") as f:
        source = f.read()
    ptx, version = compile_ptx(nvrtc, source)
    digest = hashlib.sha256(source.encode()).hexdigest()[:16]
    data = ptx + b"\0"
    lines = []
    for i in range(0, len(data), 24):
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    header = (
        "// SPDX-License-Identifier: LicenseRef-AGPL-3.0-only-OpenSSL\n"
        "// GENERATED by scripts/framegen/gen_ptx.py from framegen_kernels.cu -- do not edit.\n"
        f"// NVRTC {version}, target {ARCH}, source sha256 {digest}\n\n"
        "#pragma once\n\n"
        f"#define CHIAKI_FRAMEGEN_PTX_SOURCE_HASH \"{digest}\"\n\n"
        "static const unsigned char framegen_kernels_ptx[] = {\n" + "\n".join(lines) + "\n};\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(ptx)} bytes PTX, NVRTC {version})")


if __name__ == "__main__":
    main()
